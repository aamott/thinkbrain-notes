// `rustls-platform-verifier` ships the Kotlin half of its Android support as a
// Maven repository *inside the crate source*, so the only way to find it is to
// ask cargo where the crate was unpacked. Without this the Rust side compiles
// and links fine and then panics at the first HTTPS request — see
// `src-tauri/src/android_tls.rs`.
//
// NOTE: `gen/android/` is generated by `tauri android init` but committed. If
// it is ever regenerated, this block and the `rustls` dependency below must be
// re-applied by hand.
val rustlsVerifierMaven: File = run {
    val metadata = providers.exec {
        workingDir = projectDir
        commandLine(
            "cargo", "metadata",
            "--format-version", "1",
            "--filter-platform", "aarch64-linux-android",
            "--manifest-path", "../../../Cargo.toml"
        )
    }.standardOutput.asText.get()

    @Suppress("UNCHECKED_CAST")
    val packages = (JsonSlurper().parseText(metadata) as Map<String, Any>)["packages"]
        as List<Map<String, Any>>
    val manifest = packages.firstOrNull { it["name"] == "rustls-platform-verifier-android" }
        ?: error("rustls-platform-verifier-android is not in the Android dependency graph")
    File(File(manifest["manifest_path"] as String).parentFile, "maven")
}

// The bundled repository ships `maven-metadata-local.xml` rather than the
// `maven-metadata.xml` Gradle needs to resolve a dynamic version, so
// `latest.release` cannot work. Read the version off the directory instead of
// hardcoding one, so a cargo update of the crate does not silently leave the
// Kotlin half behind the Rust half.
val rustlsVerifierVersion: String =
    File(rustlsVerifierMaven, "rustls/rustls-platform-verifier")
        .listFiles()
        ?.filter { it.isDirectory }
        ?.map { it.name }
        ?.maxOrNull()
        ?: error("no versioned artifact under $rustlsVerifierMaven")

repositories {
    maven {
        url = uri(rustlsVerifierMaven)
        metadataSources { artifact() }
    }
}

dependencies {
    // `@aar` is required: the bundled artifact is an Android library, and
    // `metadataSources { artifact() }` above skips the POM that would otherwise
    // declare `<packaging>aar</packaging>`, so Gradle would look for a .jar.
    implementation("rustls:rustls-platform-verifier:$rustlsVerifierVersion@aar")
    implementation("androidx.webkit:webkit:1.14.0")
